import AppKit
import FluxCore
import SwiftUI

/// Opt-in: notices download links the user copies and asks, in a small floating panel,
/// whether to download them. Never downloads without a click. Skips what password
/// managers mark as concealed, Flux's own copies, and links Flux already has.
@MainActor
final class ClipboardWatcher {
    private unowned let model: AppModel
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    /// Links already offered this session, so copying one twice asks once.
    private var offered: Set<URL> = []
    private var panel: NSPanel?
    private var hideTask: Task<Void, Never>?

    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    static let visibleSeconds = 15.0

    init(model: AppModel) {
        self.model = model
    }

    func update(enabled: Bool) {
        if enabled, timer == nil {
            // Only what's copied from now on, not whatever was on the clipboard already.
            lastChange = NSPasteboard.general.changeCount
            let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.check() }
            }
            timer.tolerance = 0.25
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else if !enabled, let timer {
            timer.invalidate()
            self.timer = nil
            dismiss()
        }
    }

    /// Call after Flux itself writes to the clipboard (Copy Link).
    func ignoreCurrentContents() {
        lastChange = NSPasteboard.general.changeCount
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes), let text = pasteboard.string(forType: .string) else { return }
        let known = Set(model.downloads.filter { !$0.record.isArchived }.map(\.record.url))
        let links = ClipboardLinks.downloadCandidates(in: text).filter { !offered.contains($0) && !known.contains($0) }
        guard !links.isEmpty else { return }
        offered.formUnion(links)
        show(links)
    }

    // MARK: Panel

    private func show(_ links: [URL]) {
        dismiss()
        let view = ClipboardPrompt(
            links: links,
            onDownload: { [weak self] in
                self?.model.add(links)
                self?.dismiss()
            },
            onOptions: { [weak self] in
                guard let self else { return }
                self.dismiss()
                NSApp.activate()
                self.model.openMainWindow?()
                self.model.presentAddSheet(prefill: links.map(\.absoluteString).joined(separator: "\n"))
            },
            onClose: { [weak self] in self?.dismiss() })
        let host = NSHostingView(rootView: view.tint(FluxTheme.accent))
        let size = host.fittingSize
        let panel = NSPanel(contentRect: NSRect(origin: .zero, size: size),
                            styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
        panel.contentView = host
        panel.isOpaque = false
        panel.backgroundColor = .clear
        panel.hasShadow = true
        panel.level = .floating
        panel.hidesOnDeactivate = false
        panel.isReleasedWhenClosed = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        let screen = NSScreen.screens.first { NSMouseInRect(NSEvent.mouseLocation, $0.frame, false) } ?? NSScreen.main
        if let frame = screen?.visibleFrame {
            panel.setFrameOrigin(NSPoint(x: frame.maxX - size.width - 16, y: frame.maxY - size.height - 16))
        }
        panel.orderFrontRegardless()
        self.panel = panel
        hideTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(Self.visibleSeconds))
            guard !Task.isCancelled else { return }
            self?.dismiss()
        }
    }

    private func dismiss() {
        hideTask?.cancel()
        hideTask = nil
        panel?.orderOut(nil)
        panel = nil
    }
}

struct ClipboardPrompt: View {
    let links: [URL]
    let onDownload: () -> Void
    let onOptions: () -> Void
    let onClose: () -> Void

    private var title: String {
        guard links.count == 1, let link = links.first else { return "Download \(links.count) copied links?" }
        if MediaRouting.prefersMedia(link) { return "Download this video?" }
        return "Download \(link.lastPathComponent.removingPercentEncoding ?? link.lastPathComponent)?"
    }

    private var subtitle: String {
        let hosts = Array(Set(links.compactMap { $0.host() })).sorted()
        return hosts.count == 1 ? "Copied link from \(hosts[0])" : "From \(hosts.prefix(3).joined(separator: ", "))"
    }

    var body: some View {
        HStack(alignment: .top, spacing: 12) {
            Image(systemName: "arrow.down.circle.fill")
                .font(.system(size: 28))
                .foregroundStyle(FluxTheme.accent)
            VStack(alignment: .leading, spacing: 8) {
                VStack(alignment: .leading, spacing: 2) {
                    Text(title)
                        .font(.headline)
                        .lineLimit(2)
                        .truncationMode(.middle)
                    Text(subtitle)
                        .font(.caption)
                        .foregroundStyle(.secondary)
                        .lineLimit(1)
                }
                HStack(spacing: 8) {
                    Button("Download", action: onDownload)
                        .buttonStyle(.borderedProminent)
                    Button("Options…", action: onOptions)
                }
                .controlSize(.small)
            }
            Spacer(minLength: 0)
            Button(action: onClose) {
                Image(systemName: "xmark")
                    .font(.caption.weight(.semibold))
                    .foregroundStyle(.secondary)
            }
            .buttonStyle(.plain)
            .help("Not now")
        }
        .padding(14)
        .frame(width: 340)
        .background(.regularMaterial, in: RoundedRectangle(cornerRadius: 14, style: .continuous))
        .overlay(RoundedRectangle(cornerRadius: 14, style: .continuous).strokeBorder(.separator.opacity(0.5)))
        .accessibilityElement(children: .contain)
        .accessibilityLabel("Flux: \(title)")
    }
}
